/**
 * Navigation icons.
 *
 * Path data from Phosphor Icons (MIT, https://phosphoricons.com), trimmed to
 * the weights this app actually draws: `regular` (outlined, at rest) and
 * `fill` (the selected tab). The @phosphor-icons/react package ships all six
 * weights inside every icon module — about 4 KB each — which added 54 kB to
 * the main bundle for sixteen icons. These are the same glyphs at a quarter
 * of the cost.
 *
 * To add one: copy the icon's SVG path from phosphoricons.com (Regular, and
 * Fill if it is a tab), and pass the d attributes to createIcon.
 */

export type IconWeight = 'regular' | 'fill';

export interface IconProps extends React.SVGProps<SVGSVGElement> {
  weight?: IconWeight;
}

export type NavIcon = React.FC<IconProps>;

function createIcon(
  name: string,
  regular: readonly string[],
  fill: readonly string[] = regular,
): NavIcon {
  function Icon({ weight = 'regular', ...props }: IconProps) {
    const paths = weight === 'fill' ? fill : regular;
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox="0 0 256 256"
        fill="currentColor"
        width="1em"
        height="1em"
        aria-hidden="true"
        focusable="false"
        {...props}
      >
        {paths.map((d) => (
          <path key={d} d={d} />
        ))}
      </svg>
    );
  }
  Icon.displayName = name;
  return Icon;
}

